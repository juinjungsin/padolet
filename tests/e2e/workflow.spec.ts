import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { seed, SEED, SUPER_ADMIN } from "../support/seed.mjs";
import { joinAsParticipant, loginAsAdmin } from "./helpers";
test.beforeAll(async () => { await seed(); });

test("업무 상세·조직 구획·협업 조건·개선안 저장과 진단서", async ({ page }) => {
  await loginAsAdmin(page, SUPER_ADMIN.email);
  await page.goto(`/board/${SEED.main.id}`);
  await page.getByRole("tab", { name: "흐름도", exact: true }).click();
  await page.getByRole("button", { name: "조직 협업 템플릿", exact: true }).click();
  const details = page.getByRole("complementary", { name: "업무 상세" });
  await details.getByLabel("담당 역할", { exact: true }).fill("접수 담당자");
  await details.getByLabel("입력·시작 조건", { exact: true }).fill("고객 요청서 수신");
  await details.getByLabel("산출물·완료 결과", { exact: true }).fill("검토 요청서");
  await details.getByLabel("사용 시스템", { exact: true }).fill("ERP");
  await details.getByLabel("작업 시간(분)", { exact: true }).fill("10");
  await details.getByLabel("대기 시간(분)", { exact: true }).fill("60");
  await details.getByLabel("현재 문제점", { exact: true }).fill("ERP와 엑셀에 중복 입력");
  await details.getByLabel("개선 방향", { exact: true }).selectOption("automate");
  await details.getByLabel("개선 후 업무안", { exact: true }).fill("입력 시스템을 하나로 통합");
  await page.getByText("연결선 목록·목록으로 연결", { exact: true }).click();
  const edge = page.getByRole("list", { name: "연결선 목록" }).locator("li").first();
  await edge.getByLabel("전달 산출물", { exact: true }).fill("검토 요청서");
  await edge.getByLabel("인수·완료 조건", { exact: true }).fill("필수 정보 확인 후 접수");
  await edge.getByLabel("협업 유형", { exact: true }).selectOption("request");
  await page.getByRole("button", { name: "흐름도 저장", exact: true }).click();
  await expect(page.getByText("흐름도를 저장했습니다.", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("tab", { name: "흐름도", exact: true }).click();
  await expect(page.getByTestId("flow-canvas")).toContainText("요청 조직");
  await page.getByRole("button", { name: "단계 요청 접수", exact: true }).click();
  await expect(details.getByLabel("개선 후 업무안", { exact: true })).toHaveValue("입력 시스템을 하나로 통합");
  await expect(details.getByLabel("작업 시간(분)", { exact: true })).toHaveValue("10");
  await page.getByText(/^업무 진단 · 작업/).click();
  const diagnosis = page.getByLabel("업무 진단 결과", { exact: true });
  await expect(diagnosis).toContainText("입력된 작업 시간 합계 10분");
  await expect(diagnosis).toContainText("대기 시간이 작업 시간보다 깁니다");
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "업무 진단서 저장" }).click();
  const download = await downloadEvent;
  const report = await readFile((await download.path())!, "utf8");
  expect(report).toContain("입력 시스템을 하나로 통합");
  expect(report).toContain("필수 정보 확인 후 접수");
  expect(report).toContain("ERP와 엑셀에 중복 입력");
  const pngEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "PNG 저장", exact: true }).click();
  await (await pngEvent).saveAs(test.info().outputPath("workflow.png"));
  await page.getByRole("button", { name: "자유 배치로 전환", exact: true }).click();
  const n = page.getByRole("button", { name: "단계 요청 접수", exact: true });
  const before = await n.getAttribute("transform");
  await n.focus(); await page.keyboard.press("ArrowRight");
  await expect(n).not.toHaveAttribute("transform", before!);
  page.once("dialog", d => d.dismiss());
  await page.getByRole("button", { name: "내 업무 템플릿", exact: true }).click();
  await expect(page.getByLabel("흐름도 제목", { exact: true })).toHaveValue("조직 간 협업과 인수인계");
});

