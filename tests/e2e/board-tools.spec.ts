test("흐름도 동시 편집은 충돌을 알리고 초안을 보존", async ({ page, context }) => {
  await loginAsAdmin(page, SUPER_ADMIN.email);
  await page.goto(`/board/${SEED.main.id}`);
  await page.getByRole("tab", { name: "흐름도", exact: true }).click();
  await expect(page.getByLabel("흐름도 제목", { exact: true })).toBeEnabled();
  const other = await context.newPage();
  await other.goto(`/board/${SEED.main.id}`);
  await other.getByRole("tab", { name: "흐름도", exact: true }).click();
  await expect(other.getByLabel("흐름도 제목", { exact: true })).toBeEnabled();
  await other.getByLabel("흐름도 제목", { exact: true }).fill("다른 창의 초안");
  await page.getByLabel("흐름도 제목", { exact: true }).fill("먼저 저장한 변경");
  await page.getByRole("button", { name: "흐름도 저장", exact: true }).click();
  await expect(page.getByText("흐름도를 저장했습니다.", { exact: true })).toBeVisible();
  await other.getByRole("button", { name: "흐름도 저장", exact: true }).click();
  await expect(other.getByRole("region", { name: "작업 흐름도", exact: true }).getByRole("alert")).toContainText("다른 창에서 수정되었습니다");
  await expect(other.getByLabel("흐름도 제목", { exact: true })).toHaveValue("다른 창의 초안");
  other.once("dialog", dialog => dialog.accept());
  await other.getByRole("button", { name: "최신본 다시 열기" }).click();
  await expect(other.getByLabel("흐름도 제목", { exact: true })).toHaveValue("먼저 저장한 변경");
  await other.close();
});
