test("포스트잇 설정·순서·칸반 상태 저장, 보드 제목과 대화 정렬·삭제", async ({ page }) => {
  await loginAsAdmin(page, SUPER_ADMIN.email);
  await page.goto(`/board/${SEED.main.id}`);
  await page.getByRole("button", { name: "보드 제목 변경", exact: true }).click();
  await page.getByLabel("보드 제목", { exact: true }).fill("새 보드 제목");
  await page.getByRole("button", { name: "제목 저장" }).click();
  const card = page.locator('[data-post-id="post-pinned"]');
  await card.getByRole("button", { name: /메뉴|더보기/ }).click();
  await page.getByRole("menuitem", { name: "제목·색상·위치 변경" }).click();
  await card.getByLabel("포스트잇 제목", { exact: true }).fill("변경한 포스트잇");
  await card.getByLabel("파랑", { exact: true }).check();
  await card.getByLabel("배치 위치").fill("-3");
  await card.getByLabel("칸반 상태", { exact: true }).selectOption("doing");
  await card.getByRole("button", { name: "설정 저장" }).click();
  await expect(card.getByRole("heading", { name: "변경한 포스트잇" })).toBeVisible();
  await page.reload();
  await expect(page.getByText("새 보드 제목", { exact: true })).toBeVisible();
  await expect(card).toHaveCSS("background-color", "rgb(234, 242, 251)");
  await page.getByRole("tab", { name: "칸반", exact: true }).click();
  const doing = page.getByRole("region", { name: "진행 중", exact: true });
  await expect(doing).toContainText("변경한 포스트잇");
  await doing.getByLabel("변경한 포스트잇 칸반 상태").selectOption("done");
  await expect(page.getByRole("region", { name: "완료", exact: true })).toContainText("변경한 포스트잇");
  await page.screenshot({ path: "test-results/kanban-desktop.png" });
  await page.getByRole("tab", { name: "보드", exact: true }).first().click();
  const source = page.locator('[data-post-id="post-link"]').locator("..");
  const target = page.locator('[data-post-id="post-text"]').locator("..");
  await source.getByTitle("다른 카드 앞으로 이동").dragTo(target);
  await expect(page.getByTestId("post-board").locator("[data-post-id]").nth(1)).toHaveAttribute("data-post-id", "post-link");
  await page.getByLabel(/^정렬 —/).selectOption("title");
  const chat = page.getByTestId("chat-panel");
  await chat.getByLabel("메시지 입력", { exact: true }).fill("삭제할 대화");
  await chat.getByRole("button", { name: "보내기", exact: true }).click();
  await chat.getByLabel("대화 정렬").selectOption("latest");
  const msg = chat.locator("[data-message-id]").filter({ hasText: "삭제할 대화" });
  await expect(msg).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await msg.getByRole("button", { name: "삭제", exact: true }).click();
  await expect(msg).toHaveCount(0);
});

